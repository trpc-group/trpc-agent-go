// ToolSearchToolName is the ToolName of the tool messages that record client
// tool search results, so that event and history consumers can tell them from
// function results. The ToolID of such a message is the call_id of the search.
const ToolSearchToolName = "tool_search"

const (
	clientToolSearchDescription = "Search for and load deferred tools that are needed to continue the task. " +
		"Describe the capability that the tools must provide."
	toolSetNamespaceDescription = "Tools from the %s tool set."
)

// ToolSearchHandler selects deferred tools for one client-executed tool
// search. It must only select tools from req.Candidates and must not modify
// req. A nil result or an empty ToolIDs list loads no tools; the model is told
// that the search found nothing. An error stops the agent run without
// recording a search result. The search call then stays unanswered: a run
// with agent.WithResume calls the handler again, and other requests that
// replay the session fail until the call is answered. Return an empty result
// instead of an error to let the model continue without the tools. The
// handler should return promptly when ctx is canceled, and may be called
// concurrently for different requests.
type ToolSearchHandler func(ctx context.Context, req *ToolSearchRequest) (*ToolSearchResult, error)

// ToolSearchRequest describes one client-executed tool search call.
type ToolSearchRequest struct {
	// CallID identifies the tool_search_call answered by this search.
	CallID string
	// Arguments holds the JSON object generated by the model for the search.
	Arguments json.RawMessage
	// Query is the "query" string of Arguments, or empty when absent.
	Query string
	// Candidates lists the deferred tools of the current request that are not
	// loaded yet, sorted by ID. Only these tools can be loaded.
	Candidates []ToolSearchCandidate
}

// ToolSearchCandidate describes one deferred tool that a client-executed tool
// search can load.
type ToolSearchCandidate struct {
	// ID identifies the tool in ToolSearchResult.ToolIDs. It is the name under
	// which the agent registered and executes the tool, so it is unique in
	// the request even when tools in different namespaces share a Name.
	ID string
	// Namespace is the name of the ToolSet that provides the tool, or empty
	// for a standalone tool.
	Namespace string
	// NamespaceDescription describes the namespace, or is empty for a
	// standalone tool.
	NamespaceDescription string
	// Name is the tool name sent to the model: the original member name for a
	// namespace tool, or the declared function name for a standalone tool.
	Name string
	// Declaration is the declaration loaded for the tool, with Name set to
	// the Name field. Its schema values are shared with the tool and must not
	// be modified.
	Declaration tool.Declaration
}

// ToolSearchResult lists the tools loaded by one client-executed tool search.
type ToolSearchResult struct {
	// ToolIDs selects candidates by ToolSearchCandidate.ID. Unknown or
	// duplicate IDs are errors. Loaded tools are grouped by namespace in the
	// order of their first selection.
	ToolIDs []string
}

type toolSearchMode int

const (
	toolSearchDisabled toolSearchMode = iota
	toolSearchHosted
	toolSearchClient
)

type toolSearchConfig struct {
	mode    toolSearchMode
	handler ToolSearchHandler
}

// wireFunction is the identity of a function as the API sees it.
type wireFunction struct {
	namespace string
	name      string
}

// deferredTool is a request tool that a client tool search can load.
type deferredTool struct {
	candidate ToolSearchCandidate
	function  wireFunction
}

// toolPlan is the exposure of one request's tools.
type toolPlan struct {
	params []responses.ToolUnionParam
	// functions maps namespaced wire functions to request tool keys.
	functions map[wireFunction]string
	// flat maps the wire names of functions outside namespaces to request
	// tool keys.
	flat map[string]string
	// keys holds every request tool key.
	keys map[string]struct{}
	// deferred lists client tool search candidates in request key order.
	deferred []deferredTool
}

// projectionToolPlan resolves stable tool identities without re-evaluating
// request exposure policies or calling client search handlers.
func projectionToolPlan(request *model.Request) *toolPlan {
	if request == nil {
		return nil
	}
	plan := &toolPlan{
		functions: make(map[wireFunction]string),
		flat:      make(map[string]string),
		keys:      make(map[string]struct{}),
	}
	for key, tl := range request.Tools {
		if tl == nil || tl.Declaration() == nil {
			continue
		}
		plan.keys[key] = struct{}{}
		plan.flat[tl.Declaration().Name] = key
		if namespace, name, _, ok := itool.ToolSetMember(tl); ok {
			plan.functions[wireFunction{namespace: namespace, name: name}] = key
		}
	}
	return plan
}

// functionName maps a function call to its request tool key. A call outside
// any namespace keeps its name. A namespaced call that matches no request tool
// gets a name no request tool has, so the agent reports a missing tool instead
// of running a tool with the same bare name.
func (p *toolPlan) functionName(namespace, name string) (string, error) {
	if namespace == "" {
		return name, nil
	}
	if p == nil {
		return "", fmt.Errorf("function call %q in namespace %q needs its request to be projected", name, namespace)
	}
	if key, ok := p.functions[wireFunction{namespace: namespace, name: name}]; ok {
		return key, nil
	}
	if namespace == name {
		// A loaded standalone function reports its own name as namespace.
		if key, ok := p.flat[name]; ok {
			return key, nil
		}
	}
	unresolved := namespace + "." + name
	if _, ok := p.keys[unresolved]; ok {
		return "", fmt.Errorf("function call %q in namespace %q is ambiguous", name, namespace)
	}
	return unresolved, nil
}

// planTools exposes request tools. Without tool search, every tool is a
// top-level function exactly as before. With tool search, deferred tools are
// declared with defer_loading (hosted) or offered to the client handler
// (client), members of a ToolSet with deferred members share one namespace,
// and the tool_search tool is added when anything is deferred or history
// already contains tool search items.
func (m *Model) planTools(ctx context.Context, request *model.Request) (*toolPlan, error) {
	if m.toolSearch.mode == toolSearchDisabled {
		return plainToolPlan(request.Tools)
	}
	if m.toolSearch.mode == toolSearchClient && m.toolSearch.handler == nil {
		return nil, errors.New("openai/responses: client tool search requires a handler")
	}
	history := scanToolSearchHistory(request.Messages)
	entries, namespaced := toolEntries(ctx, request.Tools)
	p := newToolPlanner(m.toolSearch.mode == toolSearchClient, history.loaded, len(entries))
	anyDeferred := false
	for _, e := range entries {
		anyDeferred = anyDeferred || e.deferred
		p.plan.keys[e.key] = struct{}{}
		var err error
		if e.member && namespaced[e.namespace] {
			err = p.addNamespaced(e)
		} else {
			err = p.addTopLevel(e)
		}
		if err != nil {
			return nil, err
		}
	}
	if err := p.finishNamespaces(); err != nil {
		return nil, err
	}
	if anyDeferred || history.seen {
		p.plan.params = append(p.plan.params, m.toolSearchParam())
	}
	return p.plan, nil
}

func plainToolPlan(tools map[string]tool.Tool) (*toolPlan, error) {
	plan := &toolPlan{}
	if len(tools) == 0 {
		return plan, nil
	}
	params, err := convertTools(tools)
	if err != nil {
		return nil, err
	}
	plan.params = params
	return plan, nil
}

// toolEntry is a request tool with the identity that tool search exposes.
type toolEntry struct {
	key         string
	decl        *tool.Declaration
	deferred    bool
	member      bool
	namespace   string
	name        string
	description string
}

// toolEntries lists request tools in request key order and reports the
// ToolSets that have deferred members. Like convertTools, it skips nil tools
// and tools without a declaration.
func toolEntries(ctx context.Context, tools map[string]tool.Tool) ([]toolEntry, map[string]bool) {
	keys := make([]string, 0, len(tools))
	for key, t := range tools {
		if t != nil && t.Declaration() != nil {
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	entries := make([]toolEntry, 0, len(keys))
	namespaced := make(map[string]bool)
	for _, key := range keys {
		t := tools[key]
		e := toolEntry{key: key, decl: t.Declaration(), deferred: tool.ShouldDefer(ctx, t)}
		e.namespace, e.name, e.description, e.member = itool.ToolSetMember(t)
		if e.member && e.deferred {
			namespaced[e.namespace] = true
		}
		entries = append(entries, e)
	}
	return entries, namespaced
}

type namespaceGroup struct {
	description string
	tools       []responses.NamespaceToolToolUnionParam
}

// toolPlanner builds the toolPlan of one request with tool search enabled.
type toolPlanner struct {
	client bool
	// loaded holds the functions that history already loaded.
	loaded   map[wireFunction]bool
	plan     *toolPlan
	groups   map[string]*namespaceGroup
	topLevel map[string]struct{}
}

func newToolPlanner(client bool, loaded map[wireFunction]bool, size int) *toolPlanner {
	return &toolPlanner{
		client: client,
		loaded: loaded,
		plan: &toolPlan{
			functions: make(map[wireFunction]string),
			flat:      make(map[string]string),
			keys:      make(map[string]struct{}, size),
		},
		groups:   make(map[string]*namespaceGroup),
		topLevel: make(map[string]struct{}),
	}
}

func (p *toolPlanner) addTopLevel(e toolEntry) error {
	fn, err := functionToolParam(e.decl)
	if err != nil {
		return err
	}
	p.plan.flat[fn.Name] = e.key
	if e.deferred && p.client {
		p.offer(searchCandidate(e.key, fn.Name, "", "", e.decl), wireFunction{name: fn.Name})
		return nil
	}
	if e.deferred {
		fn.DeferLoading = openai.Bool(true)
	}
	p.topLevel[fn.Name] = struct{}{}
	p.plan.params = append(p.plan.params, responses.ToolUnionParam{OfFunction: &fn})
	return nil
}

func (p *toolPlanner) addNamespaced(e toolEntry) error {
	function := wireFunction{namespace: e.namespace, name: e.name}
	if other, ok := p.plan.functions[function]; ok {
		return fmt.Errorf("openai/responses: tools %q and %q are both %q in namespace %q", other, e.key, e.name, e.namespace)
	}
	p.plan.functions[function] = e.key
	description := e.description
	if strings.TrimSpace(description) == "" {
		description = fmt.Sprintf(toolSetNamespaceDescription, e.namespace)
	}
	if e.deferred && p.client {
		p.offer(searchCandidate(e.key, e.name, e.namespace, description, e.decl), function)
		return nil
	}
	member, err := namespaceFunctionParam(e.name, e.decl, e.deferred)
	if err != nil {
		return err
	}
	group, ok := p.groups[e.namespace]
	if !ok {
		group = &namespaceGroup{description: description}
		p.groups[e.namespace] = group
		p.plan.params = append(p.plan.params, responses.ToolUnionParam{
			OfNamespace: &responses.NamespaceToolParam{Name: e.namespace},
		})
	}
	group.tools = append(group.tools, responses.NamespaceToolToolUnionParam{OfFunction: &member})
	return nil
}

// offer makes a deferred tool a client search candidate unless history
// already loaded it.
func (p *toolPlanner) offer(candidate ToolSearchCandidate, function wireFunction) {
	if !p.loaded[function] {
		p.plan.deferred = append(p.plan.deferred, deferredTool{candidate: candidate, function: function})
	}
}

// finishNamespaces fills the namespace params with their members and rejects
// a namespace named like a top-level function.
func (p *toolPlanner) finishNamespaces() error {
	for _, param := range p.plan.params {
		if param.OfNamespace == nil {
			continue
		}
		name := param.OfNamespace.Name
		if _, ok := p.topLevel[name]; ok {
			return fmt.Errorf("openai/responses: tool namespace %q conflicts with a function of the same name", name)
		}
		group := p.groups[name]
		param.OfNamespace.Description = group.description
		param.OfNamespace.Tools = group.tools
	}
	return nil
}

func (m *Model) toolSearchParam() responses.ToolUnionParam {
	if m.toolSearch.mode == toolSearchClient {
		return responses.ToolUnionParam{OfToolSearch: &responses.ToolSearchToolParam{
			Execution:   responses.ToolSearchToolExecutionClient,
			Description: openai.String(clientToolSearchDescription),
			Parameters: map[string]any{
				"type": "object",
				"properties": map[string]any{
					"query": map[string]any{
						"type":        "string",
						"description": "The capability or task that the needed tools must support.",
					},
				},
				"required":             []string{"query"},
				"additionalProperties": false,
			},
		}}
	}
	return responses.ToolUnionParam{OfToolSearch: &responses.ToolSearchToolParam{}}
}

func namespaceFunctionParam(name string, decl *tool.Declaration, deferred bool) (responses.NamespaceToolToolFunctionParam, error) {
	parameters, err := functionParameters(decl)
	if err != nil {
		return responses.NamespaceToolToolFunctionParam{}, err
	}
	fn := responses.NamespaceToolToolFunctionParam{
		Name:       name,
		Parameters: parameters,
		Strict:     openai.Bool(false),
	}
	if decl.Description != "" {
		fn.Description = openai.String(decl.Description)
	}
	if deferred {
		fn.DeferLoading = openai.Bool(true)
	}
	return fn, nil
}

func searchCandidate(key, name, namespace, namespaceDescription string, decl *tool.Declaration) ToolSearchCandidate {
	candidate := ToolSearchCandidate{
		ID:          key,
		Namespace:   namespace,
		Name:        name,
		Declaration: *decl,
	}
	if namespace != "" {
		candidate.NamespaceDescription = namespaceDescription
	}
	candidate.Declaration.Name = name
	return candidate
}

// toolSearchHistory summarizes the tool search items in request history.
type toolSearchHistory struct {
	seen bool
	// loaded holds functions loaded by earlier tool_search_output items.
	loaded map[wireFunction]bool
}

func scanToolSearchHistory(messages []model.Message) toolSearchHistory {
	history := toolSearchHistory{loaded: make(map[wireFunction]bool)}
	for _, msg := range messages {
		if msg.ProviderData == nil || msg.ProviderData.Protocol != responseProvider {
			continue
		}
		var items []nativeItem
		if err := json.Unmarshal(msg.ProviderData.Payload, &items); err != nil {
			continue
		}
		for _, item := range items {
			switch item.Type {
			case outputTypeToolSearchCall:
				history.seen = true
			case outputTypeToolSearchOutput:
				history.seen = true
				for _, loaded := range item.Tools {
					markLoadedTools(history.loaded, loaded)
				}
			}
		}
	}
	return history
}

func markLoadedTools(loaded map[wireFunction]bool, raw json.RawMessage) {
	var definition struct {
		Type  string `json:"type"`
		Name  string `json:"name"`
		Tools []struct {
			Type string `json:"type"`
			Name string `json:"name"`
		} `json:"tools"`
	}
	if err := json.Unmarshal(raw, &definition); err != nil {
		return
	}
	switch definition.Type {
	case functionToolType:
		loaded[wireFunction{name: definition.Name}] = true
	case "namespace":
		for _, member := range definition.Tools {
			if member.Type == functionToolType {
				loaded[wireFunction{namespace: definition.Name, name: member.Name}] = true
			}
		}
	}
}

// clientSearchArguments returns the JSON object of tool search arguments,
// decoding arguments that a compatible service sent as a JSON string.
func clientSearchArguments(raw json.RawMessage) []byte {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) > 0 && trimmed[0] == '"' {
		var encoded string
		if err := json.Unmarshal(trimmed, &encoded); err == nil {
			return []byte(encoded)
		}
	}
	return trimmed
}

// CompleteProviderActions implements model.ProviderActionCompleter. It runs
// the client tool search handler for each client tool_search_call in response
// and returns one tool message per call. Each message carries the complete
// tool_search_output, including the definitions of the loaded tools, as
// ProviderData. A response without client tool search calls returns nil.
// Candidates are the deferred tools of request that earlier searches in its
// history have not loaded. Calls already answered in request history are
// skipped when resuming a partially persisted search round.
func (m *Model) CompleteProviderActions(
	ctx context.Context,
	request *model.Request,
	response *model.Response,
) ([]model.Message, error) {
	calls, err := pendingToolSearchCalls(response, m.Info())
	if err != nil || len(calls) == 0 {
		return nil, err
	}
	if m.toolSearch.mode != toolSearchClient || m.toolSearch.handler == nil {
		return nil, errors.New("openai/responses: the response requests a client tool search, but client tool search is not configured")
	}
	if request == nil {
		return nil, errors.New("openai/responses: client tool search requires the model request")
	}
	answered, err := answeredClientSearchCalls(request.Messages, m.Info())
	if err != nil {
		return nil, err
	}
	plan, err := m.planTools(ctx, request)
	if err != nil {
		return nil, err
	}
	messages := make([]model.Message, 0, len(calls))
	loaded := make(map[string]struct{})
	for _, call := range calls {
		if answered[call.CallID] {
			continue
		}
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		available := make([]deferredTool, 0, len(plan.deferred))
		for _, candidate := range plan.deferred {
			if _, ok := loaded[candidate.candidate.ID]; !ok {
				available = append(available, candidate)
			}
		}
		searchReq := &ToolSearchRequest{
			CallID:     call.CallID,
			Arguments:  append(json.RawMessage(nil), clientSearchArguments(call.Arguments)...),
			Candidates: make([]ToolSearchCandidate, len(available)),
		}
		for i, candidate := range available {
			searchReq.Candidates[i] = candidate.candidate
		}
		var arguments struct {
			Query string `json:"query"`
		}
		if json.Unmarshal(searchReq.Arguments, &arguments) == nil {
			searchReq.Query = arguments.Query
		}
		result, err := m.toolSearch.handler(ctx, searchReq)
		if err != nil {
			return nil, fmt.Errorf("openai/responses: client tool search %q: %w", call.CallID, err)
		}
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		message, err := m.toolSearchOutputMessage(call.CallID, available, result)
		if err != nil {
			return nil, fmt.Errorf("openai/responses: client tool search %q: %w", call.CallID, err)
		}
		if result != nil {
			for _, id := range result.ToolIDs {
				loaded[id] = struct{}{}
			}
		}
		messages = append(messages, message)
	}
	return messages, nil
}

func answeredClientSearchCalls(messages []model.Message, info model.Info) (map[string]bool, error) {
	answered := make(map[string]bool)
	for _, message := range messages {
		if message.Role != model.RoleTool || message.ProviderData == nil {
			continue
		}
		if err := providerdata.ValidateMessage(message, info); err != nil {
			return nil, fmt.Errorf("openai/responses: invalid saved search result: %w", err)
		}
		items, err := parseNativeItems(message.ProviderData.Payload, true)
		if err != nil {
			return nil, fmt.Errorf("openai/responses: invalid saved search result: %w", err)
		}
		for _, item := range items {
			if item.Type != outputTypeToolSearchOutput || item.Execution != executionClient || item.CallID != message.ToolID {
				return nil, fmt.Errorf("openai/responses: saved search result does not answer call_id %q", message.ToolID)
			}
			answered[item.CallID] = true
		}
	}
	return answered, nil
}

// pendingToolSearchCalls returns the client tool search calls recorded in a
// completed response of this model.
func pendingToolSearchCalls(response *model.Response, info model.Info) ([]nativeItem, error) {
	if response == nil || response.IsPartial {
		return nil, nil
	}
	var calls []nativeItem
	for _, choice := range response.Choices {
		data := choice.Message.ProviderData
		if data == nil {
			continue
		}
		if data.Protocol != info.ProviderDataProtocol || data.Model != info.Name {
			return nil, fmt.Errorf("openai/responses: provider data belongs to protocol %q and model %q, not %q and %q",
				data.Protocol, data.Model, info.ProviderDataProtocol, info.Name)
		}
		items, err := parseNativeItems(data.Payload, true)
		if err != nil {
			return nil, fmt.Errorf("openai/responses: invalid provider data items: %w", err)
		}
		for _, item := range items {
			if item.Type == outputTypeToolSearchCall && item.Execution == executionClient {
				calls = append(calls, item)
			}
		}
	}
	return calls, nil
}

type loadedFunction struct {
	Type         string         `json:"type"`
	Name         string         `json:"name"`
	Description  string         `json:"description,omitempty"`
	DeferLoading bool           `json:"defer_loading"`
	Parameters   map[string]any `json:"parameters"`
	Strict       bool           `json:"strict"`
}

type loadedNamespace struct {
	Type        string           `json:"type"`
	Name        string           `json:"name"`
	Description string           `json:"description"`
	Tools       []loadedFunction `json:"tools"`
}

type toolSearchOutputItem struct {
	Type      string `json:"type"`
	Execution string `json:"execution"`
	CallID    string `json:"call_id"`
	Status    string `json:"status"`
	Tools     []any  `json:"tools"`
}

func (m *Model) toolSearchOutputMessage(
	callID string,
	available []deferredTool,
	result *ToolSearchResult,
) (model.Message, error) {
	byID := make(map[string]deferredTool, len(available))
	for _, candidate := range available {
		byID[candidate.candidate.ID] = candidate
	}
	output := toolSearchOutputItem{
		Type:      outputTypeToolSearchOutput,
		Execution: executionClient,
		CallID:    callID,
		Status:    "completed",
		Tools:     []any{},
	}
	var ids []string
	if result != nil {
		ids = result.ToolIDs
	}
	namespaces := make(map[string]*loadedNamespace)
	selected := make(map[string]struct{}, len(ids))
	for _, id := range ids {
		candidate, ok := byID[id]
		if !ok {
			return model.Message{}, fmt.Errorf("tool %q is not a search candidate", id)
		}
		if _, ok := selected[id]; ok {
			return model.Message{}, fmt.Errorf("tool %q is selected more than once", id)
		}
		selected[id] = struct{}{}
		parameters, err := functionParameters(&candidate.candidate.Declaration)
		if err != nil {
			return model.Message{}, err
		}
		function := loadedFunction{
			Type:         functionToolType,
			Name:         candidate.function.name,
			Description:  candidate.candidate.Declaration.Description,
			DeferLoading: true,
			Parameters:   parameters,
		}
		if candidate.function.namespace == "" {
			output.Tools = append(output.Tools, function)
			continue
		}
		namespace, ok := namespaces[candidate.function.namespace]
		if !ok {
			namespace = &loadedNamespace{
				Type:        "namespace",
				Name:        candidate.function.namespace,
				Description: candidate.candidate.NamespaceDescription,
			}
			namespaces[namespace.Name] = namespace
			output.Tools = append(output.Tools, namespace)
		}
		namespace.Tools = append(namespace.Tools, function)
	}
	payload, err := json.Marshal([]toolSearchOutputItem{output})
	if err != nil {
		return model.Message{}, fmt.Errorf("marshal tool_search_output: %w", err)
	}
	loadedIDs := append([]string{}, ids...)
	content, err := json.Marshal(struct {
		LoadedTools []string `json:"loaded_tools"`
	}{LoadedTools: loadedIDs})
	if err != nil {
		return model.Message{}, fmt.Errorf("marshal tool search summary: %w", err)
	}
	return model.Message{
		Role:     model.RoleTool,
		ToolID:   callID,
		ToolName: ToolSearchToolName,
		Content:  string(content),
		ProviderData: &model.ProviderData{
			Protocol: responseProvider,
			Model:    m.name,
			Payload:  payload,
		},
	}, nil
}

